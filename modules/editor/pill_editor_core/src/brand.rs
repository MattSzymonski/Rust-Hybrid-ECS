#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_mark_covers_a_sensible_share_of_its_box() {
        let ink = MARK_ALPHA
            .iter()
            .map(|coverage| *coverage as u64)
            .sum::<u64>();
        let share = ink as f32 / (MARK_ALPHA.len() * 255) as f32;
        assert!(
            (0.15..0.85).contains(&share),
            "the mark's ink covers {share:.3} of the box"
        );
    }

    #[test]
    fn the_mark_leaves_its_border_empty() {
        for index in 0..MARK_SIDE {
            assert_eq!(MARK_ALPHA[index], 0, "top border texel {index}");
            assert_eq!(MARK_ALPHA[(MARK_SIDE - 1) * MARK_SIDE + index], 0);
            assert_eq!(MARK_ALPHA[index * MARK_SIDE], 0);
            assert_eq!(MARK_ALPHA[index * MARK_SIDE + MARK_SIDE - 1], 0);
        }
    }

    #[test]
    fn the_mark_carries_ink_in_both_halves() {
        // One pill half is an outline and the other is solid, so the two
        // quadrants on opposite corners of the box must both carry ink. If one
        // of them is empty, the path was clipped when it was rendered.
        let half = MARK_SIDE / 2;
        let mut top_right = 0u64;
        let mut bottom_left = 0u64;
        for row in 0..MARK_SIDE {
            for column in 0..MARK_SIDE {
                let ink = MARK_ALPHA[row * MARK_SIDE + column] as u64;
                if row < half && column >= half {
                    top_right += ink;
                }
                if row >= half && column < half {
                    bottom_left += ink;
                }
            }
        }
        let quadrant = (half * half * 255) as u64;
        assert!(top_right > quadrant / 10, "the outline half lost its ink");
        assert!(bottom_left > quadrant / 10, "the solid half lost its ink");
    }

    #[test]
    fn the_image_carries_the_mask_as_alpha() {
        let image = mark_color_image();
        assert_eq!(image.size, [MARK_SIDE, MARK_SIDE]);
        assert_eq!(image.pixels.len(), MARK_SIDE * MARK_SIDE);
        for (pixel, coverage) in image.pixels.iter().zip(MARK_ALPHA.iter()) {
            assert_eq!(pixel.a(), *coverage);
            // `from_white_alpha` multiplies the white channels by the alpha,
            // so red, green and blue all equal the alpha here.
            assert_eq!(pixel.r(), *coverage);
            assert_eq!(pixel.g(), *coverage);
            assert_eq!(pixel.b(), *coverage);
        }
    }
}
