//! The semantic rendering protocol and its two renderers.
//!
//! # Responsibilities
//!
//! - Define [`SemanticRole`], the meaning-only vocabulary a `#[message(...)]`
//!   definition is written in.
//! - Declare [`MessageRenderer`] and [`EngineMessage`], the seam between a
//!   generated error definition and the medium that draws it.
//! - Provide the two renderers the engine ships: plain text, and terminal text
//!   with styling.
//!
//! # Design
//!
//! Roles describe meaning, never appearance, so an error definition never names
//! a colour or a glyph. A renderer owns that decision for its medium, which is
//! why styling lives only here.

use super::*;

// =============================================================================
// Semantic Rendering Protocol
// =============================================================================

/// Semantic role of one message token.
///
/// Roles describe meaning, never appearance. The renderer decides how each
/// role looks in its target environment.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SemanticRole {
    /// General engine objects: `Scene`, `Component`, `System`, `Resource`.
    General,
    /// Specific engine objects or types: `Texture`, `Surface`, `Handle`.
    Specific,
    /// Module-level concepts: `Engine`, `Renderer`, `Window`.
    Module,
    /// User or domain names: file paths, scene names, symbol names.
    Name,
}

/// Sink for one semantically rendered error message.
///
/// Generated `EngineMessage` implementations call this protocol directly;
/// no intermediate vector or reconstructed string is ever created.
pub trait MessageRenderer {
    /// Write one plain-text fragment.
    ///
    /// # Errors
    ///
    /// Returns an error if the underlying writer fails.
    fn text(&mut self, text: &str) -> fmt::Result;

    /// Write one value under a semantic role.
    ///
    /// # Errors
    ///
    /// Returns an error if the underlying writer fails.
    fn styled(&mut self, role: SemanticRole, value: &dyn fmt::Display) -> fmt::Result;

    /// Write one plain dynamic value.
    ///
    /// # Errors
    ///
    /// Returns an error if the underlying writer fails.
    fn value(&mut self, value: &dyn fmt::Display) -> fmt::Result;

    /// Write the debug representation of one dynamic value.
    ///
    /// # Errors
    ///
    /// Returns an error if the underlying writer fails.
    fn debug_value(&mut self, value: &dyn fmt::Debug) -> fmt::Result;
}

/// Rendering interface generated by `#[engine_error]` for every error enum.
///
/// Generated implementations render the single semantic message definition
/// through [`MessageRenderer`], so plain and styled output always agree.
pub trait EngineMessage {
    /// Render the single semantic message definition into `renderer`.
    ///
    /// # Errors
    ///
    /// Returns an error if `renderer` reports a write failure.
    fn render_message(&self, renderer: &mut dyn MessageRenderer) -> fmt::Result;

    /// Convenience rendering into the plain renderer, for logs and tests.
    ///
    /// # Examples
    ///
    /// ```
    /// use pill_core::error::{BuildError, EngineMessage};
    ///
    /// let message = BuildError::Cancelled.to_plain_message();
    /// assert_eq!(
    ///     message,
    ///     "build cancelled: sources changed again during compilation"
    /// );
    /// ```
    fn to_plain_message(&self) -> String {
        let mut output = String::new();
        let mut renderer = PlainMessageRenderer {
            output: &mut output,
        };
        // Rendering into a String can never fail.
        let _ = self.render_message(&mut renderer);
        output
    }
}

/// Renderer that ignores semantic roles and keeps values verbatim.
///
/// Used by tests, logs, and any non-styled environment; every message
/// degrades cleanly to plain text.
pub struct PlainMessageRenderer<'a, W> {
    output: &'a mut W,
}

impl<W: fmt::Write> PlainMessageRenderer<'_, W> {
    /// Wrap a writer for plain rendering.
    ///
    /// # Examples
    ///
    /// ```
    /// use pill_core::error::{BuildError, EngineMessage, PlainMessageRenderer};
    ///
    /// let mut output = String::new();
    /// {
    ///     let mut renderer = PlainMessageRenderer::new(&mut output);
    ///     BuildError::Cancelled.render_message(&mut renderer).unwrap();
    /// }
    /// assert_eq!(
    ///     output,
    ///     "build cancelled: sources changed again during compilation"
    /// );
    /// ```
    pub fn new(output: &mut W) -> PlainMessageRenderer<'_, W> {
        PlainMessageRenderer { output }
    }
}

impl<W: fmt::Write> MessageRenderer for PlainMessageRenderer<'_, W> {
    fn text(&mut self, text: &str) -> fmt::Result {
        self.output.write_str(text)
    }

    fn styled(&mut self, _role: SemanticRole, value: &dyn fmt::Display) -> fmt::Result {
        write!(self.output, "{value}")
    }

    fn value(&mut self, value: &dyn fmt::Display) -> fmt::Result {
        write!(self.output, "{value}")
    }

    fn debug_value(&mut self, value: &dyn fmt::Debug) -> fmt::Result {
        write!(self.output, "{value:?}")
    }
}

/// Terminal renderer carrying the project's visual style per semantic role.
///
/// This module owns all terminal appearance decisions; error definitions
/// never reference colors or ANSI styling.
pub struct TerminalMessageRenderer<'a, W> {
    output: &'a mut W,
}

impl<W: fmt::Write> TerminalMessageRenderer<'_, W> {
    /// Wrap a writer for styled terminal rendering.
    ///
    /// # Examples
    ///
    /// ```
    /// use pill_core::error::{BuildError, EngineMessage, TerminalMessageRenderer};
    ///
    /// let mut output = String::new();
    /// {
    ///     let mut renderer = TerminalMessageRenderer::new(&mut output);
    ///     BuildError::Cancelled.render_message(&mut renderer).unwrap();
    /// }
    /// assert!(output.contains("build cancelled"));
    /// ```
    pub fn new(output: &mut W) -> TerminalMessageRenderer<'_, W> {
        TerminalMessageRenderer { output }
    }
}

impl<W: fmt::Write> MessageRenderer for TerminalMessageRenderer<'_, W> {
    fn text(&mut self, text: &str) -> fmt::Result {
        self.output.write_str(text)
    }

    fn styled(&mut self, role: SemanticRole, value: &dyn fmt::Display) -> fmt::Result {
        // The semantic roles map onto the crate's one styling vocabulary, so
        // a color is defined once and the renderer owns no palette of its own.
        let value = value.to_string();
        let styled = match role {
            SemanticRole::General => value.general_object_style(),
            SemanticRole::Specific => value.specific_object_style(),
            SemanticRole::Module => value.module_object_style(),
            SemanticRole::Name => value.name_style(),
        };
        self.output.write_str(&styled)
    }

    fn value(&mut self, value: &dyn fmt::Display) -> fmt::Result {
        write!(self.output, "{value}")
    }

    fn debug_value(&mut self, value: &dyn fmt::Debug) -> fmt::Result {
        write!(self.output, "{value:?}")
    }
}
